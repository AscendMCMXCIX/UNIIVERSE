"""Formats results/results.json as results/REPORT.md. Computes nothing new: every number comes from run_all.py."""
from __future__ import annotations

import json
import sys
from pathlib import Path


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def ci(c: dict, scale: float = 1.0, d: int = 4, unit: str = "") -> str:
    lo, hi = c["ci95"]
    return f"{c['mean'] * scale:+.{d}f}{unit} [{lo * scale:+.{d}f}, {hi * scale:+.{d}f}]"


def verdict(c: dict, below_zero: bool = True) -> str:
    lo, hi = c["ci95"]
    if below_zero:
        return "yes" if hi < 0 else ("no (better on average, interval includes zero)" if c["mean"] < 0 else "no")
    return "yes" if lo > 0 else ("no (better on average, interval includes zero)" if c["mean"] > 0 else "no")


def main(results_dir: str) -> None:
    r = json.loads((Path(results_dir) / "results.json").read_text())
    d, rq1, picks, bans = r["data"], r["rq1"], r["rq2_rq3_picks"], r["rq4_bans"]
    comp = rq1["comparisons"]
    lines: list[str] = []
    w = lines.append
    w("# Draft Intelligence pilot: results")
    w("")
    w("Generated by `src/report.py` from `results/results.json`, under the protocol frozen in commit `86589ee` (`PROTOCOL.md`).")
    w("")
    w("## Data")
    w("")
    w(f"- {d['games']:,} professional games with complete drafts, {d['first']} to {d['last']}; {d['champions']} champions; {d['fearlessTournaments']} Fearless tournaments detected.")
    w(f"- Development period: {d['devGames']:,} games (before 2025). Test period: {d['testGames']:,} games (2025-01-01 to 2026-08-31), by tier: " + ", ".join(f"{k} {v:,}" for k, v in d["testByTier"].items()) + ".")
    w(f"- Elo chosen on the development period: K = {r['elo']['k']}, blue term {r['elo']['blueBonus']} points.")
    w(f"- Unreviewed champion table: traits for {d['championsWithTraits']} of {d['champions']} champions, role priors for {d['championsWithRolePrior']}.")
    w("")
    w("## RQ1: does team comfort predict winning beyond strength and side?")
    w("")
    w("| Model | Inputs | Test log loss | Brier | AUC |")
    w("| --- | --- | --- | --- | --- |")
    names = {"M0": "side only", "M1": "+ Elo", "Mmeta": "M1 + meta win rate (basic statistics)", "M2": "M1 + team comfort", "M3": "M1 + comfort + meta", "M3traits": "M3 + unreviewed traits (exploratory)"}
    for k, label in names.items():
        m = rq1[k]
        w(f"| {k} | {label} | {m['logLoss']:.4f} | {m['brier']:.4f} | {m['auc']:.3f} |")
    w("")
    w("Differences in test log loss (negative is better), mean with 95% interval from 1,000 resamples of series:")
    w("")
    w("| Comparison | All tiers | Primary tier only | Better? (all tiers) |")
    w("| --- | --- | --- | --- |")
    labels = {
        "M2_minus_M1": "Comfort added to Elo (primary)", "M3_minus_Mmeta": "Comfort added to basic statistics",
        "Mmeta_minus_M1": "Basic statistics added to Elo", "M2_minus_Mmeta": "Comfort instead of basic statistics",
        "M1_minus_M0": "Elo added to side", "M3traits_minus_M3": "Traits added to M3 (exploratory)",
    }
    for k, label in labels.items():
        w(f"| {label} | {ci(comp[k])} | {ci(rq1['comparisonsPrimaryTier'][k])} | {verdict(comp[k])} |")
    w("")
    coef = rq1["M3"]["coefficients"]
    w(f"M3 coefficients (log-odds of a blue win per unit): Elo difference {coef.get('elo_diff', 0):.5f} per point, comfort difference {coef.get('comfort_diff', 0):.3f}, meta difference {coef.get('meta_diff', 0):.3f}.")
    w("")
    w("Calibration of M3 on the test period (predicted vs observed blue win rate, by tenth):")
    w("")
    w("| Predicted | Observed | Games |")
    w("| --- | --- | --- |")
    for b in rq1["M3"]["calibration"]:
        w(f"| {b['predicted']:.3f} | {b['observed']:.3f} | {b['n']:,} |")
    w("")
    w("## RQ2 and RQ3: anticipating picks, and coverage of enemy replies")
    w("")
    w(f"{picks['n']:,} test-period picks; weights fitted on {picks['devN']:,} development picks (a fixed 30% sample of 2023 to 2024 games).")
    w("")
    w("| Scorer | Top 1 | Top 5 | Top 10 | Top 15 | Top 20 | Mean reciprocal rank |")
    w("| --- | --- | --- | --- | --- | --- | --- |")
    for k in ("random", "popularity", "comfort", "mixWithoutRole", "mix"):
        s = picks["scorers"][k]
        w(f"| {k} | {pct(s['top1'])} | {pct(s['top5'])} | {pct(s['top10'])} | {pct(s['top15'])} | {pct(s['top20'])} | {s['mrr']:.3f} |")
    w("")
    w(f"- Primary: Mix minus Popularity, top 5: {ci(picks['primaryDiff_mix_minus_popularity_top5'], 100, 1, ' points')}.")
    w(f"- Mix minus Comfort, top 5: {ci(picks['diff_mix_minus_comfort_top5'], 100, 1, ' points')}.")
    w(f"- Role fit's own effect (Mix minus Mix without role), top 5: {ci(picks['diff_role_effect_top5'], 100, 1, ' points')}.")
    mw = picks["weights"]["mix"]
    w(f"- Mix weights: log popularity {mw['logPopularity']:.3f}, log comfort {mw['logComfort']:.3f}, role fit {mw['roleFit']:.3f}.")
    w("")
    w("Top-5 hit rate by pick slot (draft order: B1, R1, R2, B2, B3, R3, then R4, B4, B5, R5):")
    w("")
    w("| Slot | Random | Popularity | Comfort | Mix |")
    w("| --- | --- | --- | --- | --- |")
    for slot, v in picks["bySlot"].items():
        w(f"| {slot} | {pct(v['random'])} | {pct(v['popularity'])} | {pct(v['comfort'])} | {pct(v['mix'])} |")
    w("")
    w("## RQ4: anticipating bans")
    w("")
    w("| Scorer | Top 1 | Top 5 | Top 10 | Phase 1 top 5 | Phase 2 top 5 |")
    w("| --- | --- | --- | --- | --- | --- |")
    for k in ("random", "popularity", "comfort", "mixWithoutRole", "mix"):
        s = bans["scorers"][k]
        w(f"| {k} | {pct(s['top1'])} | {pct(s['top5'])} | {pct(s['top10'])} | {pct(bans['byPhase']['phase1'][k])} | {pct(bans['byPhase']['phase2'][k])} |")
    w("")
    w(f"For bans, Comfort is the opponent's comfort. Mix minus Popularity, top 5: {ci(bans['primaryDiff_mix_minus_popularity_top5'], 100, 1, ' points')}.")
    w("")
    w("## Decision rules (frozen in PROTOCOL.md)")
    w("")
    rule3 = picks["primaryDiff_mix_minus_popularity_top5"]
    cov20 = picks["scorers"]["mix"]["top20"]
    w("| Rule | Result |")
    w("| --- | --- |")
    w(f"| 1. Pool fit holds (M2 better than M1, interval below zero) | {verdict(comp['M2_minus_M1'])} |")
    w(f"| 2. Comfort beats basic statistics (M3 better than Mmeta, interval below zero) | {verdict(comp['M3_minus_Mmeta'])} |")
    w(f"| 3. Candidate model useful (Mix beats Popularity on top 5 by at least 5 points, interval above zero) | {'yes' if rule3['ci95'][0] > 0 and rule3['mean'] >= 0.05 else 'no'} ({100 * rule3['mean']:+.1f} points) |")
    w(f"| 4. Pruned enemy search viable (Mix coverage at 20 at least 75%) | {'yes' if cov20 >= 0.75 else 'no'} ({pct(cov20)}) |")
    w("")
    w("## Exploratory (added after the first run; not decision inputs)")
    w("")
    w("Coverage of actual picks by larger candidate sets, and an enemy model without the opponent's comfort (the realistic case when the opponent is unknown, as in Normal Draft and Flex):")
    w("")
    w("| Scorer | Top 20 | Top 30 | Top 40 | Top 50 |")
    w("| --- | --- | --- | --- | --- |")
    for k in ("popularity", "mix", "popularityRoleExploratory"):
        s = picks["scorers"].get(k)
        if s and "top30" in s:
            w(f"| {k} | {pct(s['top20'])} | {pct(s['top30'])} | {pct(s['top40'])} | {pct(s['top50'])} |")
    diag = rq1.get("featureDiagnosticsExploratory")
    if diag:
        w("")
        cd, corr = diag["comfort_diff"], diag["corr_with_blue_win"]
        w(f"RQ1 feature check (test period): comfort difference mean {cd['mean']:+.3f}, standard deviation {cd['std']:.3f}, 10th to 90th percentile {cd['p10']:+.3f} to {cd['p90']:+.3f}. Correlation with a blue win: comfort {corr['comfort_diff']:+.3f}, meta {corr['meta_diff']:+.3f}, Elo {corr['elo_diff']:+.3f}; comfort with Elo {diag['corr_comfort_elo']:+.3f}.")
    w("")
    w(f"Runtime: {r['runtimeSeconds']} s.")
    (Path(results_dir) / "REPORT.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).resolve().parents[1] / "results"))
